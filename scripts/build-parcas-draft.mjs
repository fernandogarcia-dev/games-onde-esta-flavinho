function normalize(rows) {
  const out = [];
  const seen = new Set();
  for (const r of rows) {
    if (!Array.isArray(r) || r.length < 6) continue;
    const [id, name, blurb, easy, medium, hard] = r;
    if (!id || id.includes("skip") || seen.has(id)) continue;
    if (!easy || easy.length < 1) continue;
    seen.add(id);
    out.push({
      id: String(id).trim(),
      name: String(name).trim(),
      blurb: String(blurb).trim(),
      clues: {
        easy: easy.slice(0, 3),
        medium: (medium || []).slice(0, 3),
        hard: (hard || []).slice(0, 3),
      },
    });
  }
  return out;
}

